## Helper functions used to render live output in the slides

#' Render a covr coverage object as HTML with coloured source lines
#'
#' Lines that were executed by tests are shown in green, lines that were
#' never executed in red, and non-executable lines (comments, roxygen,
#' braces) without colour. Similar to what covr::report() shows, but
#' lightweight enough to embed in a reveal.js slide.
#'
#' @param cov A `coverage` object returned by `covr::package_coverage()`.
#' @param pkg_path Path to the package root, used to read source files.
#' @param from_line Integer; first line of each file to show (to skip
#'     long roxygen headers). Default: 1.
#'
#' @return An HTML string (use in a chunk with `output: asis`).
render_coverage_html <- function(cov, pkg_path, from_line = 1) {
    tally <- covr::tally_coverage(cov, by = "line")
    files <- unique(tally$filename)

    escape <- function(x) {
        x <- gsub("&", "&amp;", x, fixed = TRUE)
        x <- gsub("<", "&lt;", x, fixed = TRUE)
        gsub(">", "&gt;", x, fixed = TRUE)
    }

    blocks <- vapply(files, function(f) {
        src <- readLines(file.path(pkg_path, f), warn = FALSE)
        hits <- rep(NA_integer_, length(src))
        ft <- tally[tally$filename == f, ]
        hits[ft$line] <- ft$value

        idx <- seq(from_line, length(src))
        cls <- ifelse(is.na(hits[idx]), "",
                      ifelse(hits[idx] > 0, " covr-covered", " covr-missed"))
        hit_lab <- ifelse(is.na(hits[idx]), "", paste0(hits[idx], "x"))

        lines <- sprintf(
            '<div class="covr-line%s"><span class="covr-ln">%d</span><span class="covr-hits">%s</span><span>%s</span></div>',
            cls, idx, hit_lab, escape(src[idx])
        )
        paste0('<div class="covr-file">', f, "</div>",
               paste(lines, collapse = "\n"))
    }, character(1))

    paste0('<div class="covr-report">', paste(blocks, collapse = "\n"),
           "</div>")
}

#' Render the package anatomy (file tree + descriptions) as HTML
#'
#' Used on the overview slide and on the transition slides between
#' sections, where the file(s)/folder(s) covered next are highlighted and
#' everything else is dimmed.
#'
#' @param highlight Character vector with the names of the items to
#'     highlight (as in `anatomy$item`). If NULL (default), nothing is
#'     highlighted or dimmed.
#'
#' @return An HTML string (use in a chunk with `output: asis`).
render_anatomy <- function(highlight = NULL) {
    anatomy <- data.frame(
        tree = c(
            "toyBioc/", "├── DESCRIPTION", "├── NAMESPACE", "├── NEWS.md",
            "├── README.md", "├── R/", "├── man/", "├── tests/",
            "│   ├── testthat.R", "│   └── testthat/", "├── src/  (optional)",
            "├── data/", "├── inst/", "│   ├── extdata/", "│   └── scripts/",
            "└── vignettes/"
        ),
        item = c(
            "root", "DESCRIPTION", "NAMESPACE", "NEWS.md", "README.md", "R",
            "man", "tests", "tests", "tests", "src", "data", "inst", "inst",
            "inst", "vignettes"
        )
    )
    descriptions <- c(
        DESCRIPTION = "<code>DESCRIPTION</code>: metadata",
        NAMESPACE = "<code>NAMESPACE</code>: what's imported and exported",
        R = "<code>R/</code>: R code",
        man = "<code>man/</code>: documentation (generated by roxygen2)",
        tests = "<code>tests/</code>: unit tests",
        src = "<code>src/</code>: compiled code (C/C++, Rust), <em>optional</em>",
        data = "<code>data/</code>: R objects (<code>.rda</code>) for examples",
        inst = "<code>inst/</code>: files installed as they are",
        vignettes = "<code>vignettes/</code>: long-form documentation",
        README.md = "<code>README.md</code>, <code>NEWS.md</code>: other files"
    )

    state <- function(items) {
        if (is.null(highlight)) return(rep("", length(items)))
        ifelse(items %in% highlight, " anatomy-hl", " anatomy-dim")
    }

    tree_cls <- state(anatomy$item)
    tree_cls[anatomy$item == "root"] <- ""
    tree <- sprintf('<span class="anatomy-line%s">%s</span>', tree_cls,
                    anatomy$tree)

    ## README.md and NEWS.md share one description line
    desc_cls <- state(names(descriptions))
    if (any(c("README.md", "NEWS.md") %in% highlight)) {
        desc_cls[names(descriptions) == "README.md"] <- " anatomy-hl"
    }
    desc <- sprintf('<li class="%s">%s</li>', trimws(desc_cls), descriptions)

    paste0(
        '```{=html}\n<div class="anatomy">',
        '<pre class="anatomy-tree">', paste(tree, collapse = ""), "</pre>",
        '<ul class="anatomy-desc">', paste(desc, collapse = "\n"), "</ul>",
        "</div>\n```\n"
    )
}
